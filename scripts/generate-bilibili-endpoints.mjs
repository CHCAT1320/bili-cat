import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SOURCE =
  "C:/Users/10952/Downloads/bilibili-api-python-17.4.2-src/bilibili_api_python-17.4.2/bilibili_api/data/api";

const source = process.argv[2] ?? DEFAULT_SOURCE;
const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "../src/bilibili/endpoints.ts");

function toParamType(spec) {
  const match = String(spec).match(/^\s*([A-Za-z_[\]]+)\s*:/);
  const raw = (match ? match[1] : "unknown").toLowerCase();
  if (raw === "int" || raw === "float" || raw === "num") return "number";
  if (raw === "str" || raw === "string" || raw === "const") return "string";
  if (raw === "bool") return "boolean";
  if (raw.includes("list") || raw.includes("[")) return "array";
  return "unknown";
}

function mapParams(source) {
  if (!source || typeof source !== "object") return null;
  const entries = Object.entries(source).map(([key, spec]) => [
    key,
    toParamType(spec),
  ]);
  if (entries.length === 0) return null;
  return entries;
}

function collect(node, out) {
  if (!node || typeof node !== "object") return;
  if (typeof node.url === "string") {
    out.push(node);
    return;
  }
  for (const value of Object.values(node)) collect(value, out);
}

function normalize(endpoint) {
  const result = {
    url: endpoint.url,
    method: String(endpoint.method).toUpperCase(),
  };
  for (const flag of [
    "wbi",
    "dm",
    "sign",
    "no_csrf",
    "json_body",
    "ignore_code",
  ]) {
    if (endpoint[flag]) result[flag] = true;
  }
  // 源 JSON 里部分接口漏标 wbi（Python 侧是在代码里传 wbi=True），
  // URL 含 /wbi/ 的接口一律需要 w_rid 签名。
  if (result.url.includes("/wbi/")) result.wbi = true;
  if (endpoint.verify === true || endpoint.verify === "true") result.verify = true;
  if (typeof endpoint.data === "string") result.dataRaw = true;
  const params = mapParams(endpoint.params);
  if (params) result.params = params;
  if (typeof endpoint.data === "object") {
    const data = mapParams(endpoint.data);
    if (data) result.data = data;
  }
  const query = mapParams(endpoint.query);
  if (query) result.query = query;
  const files = mapParams(endpoint.files);
  if (files) result.files = files;
  return result;
}

const tree = {};
const all = [];

for (const file of readdirSync(source).sort()) {
  if (!file.endsWith(".json")) continue;
  const name = file.replace(/\.json$/, "");
  const parsed = JSON.parse(readFileSync(join(source, file), "utf8"));
  const endpoints = [];
  collect(parsed, endpoints);
  for (const endpoint of endpoints) all.push(normalize(endpoint));
  tree[name] = prune(parsed);
}

function prune(node) {
  if (typeof node?.url === "string") return normalize(node);
  const result = {};
  for (const [key, value] of Object.entries(node ?? {})) {
    if (value && typeof value === "object") result[key] = prune(value);
  }
  return result;
}

function key(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function emitParams(entries, indent) {
  const pad = " ".repeat(indent);
  return entries
    .map(([k, v]) => `${pad}${key(k)}: ${JSON.stringify(v)},`)
    .join("\n");
}

function emit(node, indent) {
  const pad = " ".repeat(indent);
  if (node.url !== undefined) {
    const lines = [
      `${pad}{`,
      `${pad}  url: ${JSON.stringify(node.url)},`,
      `${pad}  method: ${JSON.stringify(node.method)},`,
    ];
    for (const flag of [
      "verify",
      "wbi",
      "dm",
      "sign",
      "no_csrf",
      "json_body",
      "ignore_code",
      "dataRaw",
    ]) {
      if (node[flag]) lines.push(`${pad}  ${flag}: true,`);
    }
    for (const field of ["params", "data", "query", "files"]) {
      if (!node[field]) continue;
      lines.push(`${pad}  ${field}: {`);
      lines.push(emitParams(node[field], indent + 4));
      lines.push(`${pad}  },`);
    }
    lines.push(`${pad}}`);
    return lines.join("\n");
  }
  const body = Object.entries(node)
    .map(([k, v]) => `${pad}  ${key(k)}: ${emit(v, indent + 2).trimStart()},`)
    .join("\n");
  return `{\n${body}\n${pad}}`;
}

const header = `// AUTO-GENERATED by scripts/generate-bilibili-endpoints.mjs — do not edit by hand.
// Endpoint facts (URL, method, parameter names and types) extracted from
// bilibili-api-python v17.4.2 (GPL-3.0) — https://github.com/Nemo2011/bilibili-api
// ${all.length} endpoints from ${Object.keys(tree).length} modules.

import type { EndpointTree } from "./types";

export const API = ${emit(tree, 0)} as const satisfies EndpointTree;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, header, "utf8");
console.log(`wrote ${outFile} (${all.length} endpoints)`);
